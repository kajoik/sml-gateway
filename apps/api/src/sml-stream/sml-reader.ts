const cleanHex = hexDump
  .replace(/0x/g, "")
  .replace(/,/g, "")
  .replace(/\s*/g, "")
  .replace(/\{([0-9a-fA-F]{2})\}/g, "$1")
  .toLowerCase();

const options = {
  protocol: "SmlProtocol",
  protocolSmlIgnoreInvalidCRC: false,
  obisNameLanguage: "en",
  logger: console.log,
};

function parseSml() {
  return new Promise<ObisEntry[]>((resolve, reject) => {
    const smt = new SmlProtocol(options, (err: any, data: any) => {
      if (err) return reject(err);

      const result = Object.entries(data).map(([obisId, entry]) => {
        if (!(entry instanceof ObisMeasurement)) {
          throw new Error(
            "obisMeasurement should be an instance of ObisMeasurement",
          );
        }
        const obisMeasurementNames = ObisNames.resolveObisName(entry, "en");
        return {
          obisId,
          ...obisMeasurementNames,
          values: entry.values,
        };
      });
      resolve(result);
    });

    smt.handleMessage(cleanHex);
  });
}

parseSml();

setInterval(async () => {
  const obisEntries = await parseSml();
  rpc.send({ ts: Date.now(), obisEntries });
}, 1000);
